import { _electron as electron, expect } from '@playwright/test';
import { build } from 'esbuild';
import { mkdtemp, readFile, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { resolve, join } from 'node:path';
import { pathToFileURL } from 'node:url';
import { createHash } from 'node:crypto';

const expectedScale = Number(process.argv[2]);
expect([1, 1.25, 1.5]).toContain(expectedScale);
const work = await mkdtemp(join(resolve('work'), 'phase-6-layout-'));
const profile = await mkdtemp(join(tmpdir(), 'phase-6-layout-'));
const helper = join(work, 'fixture-api.mjs');
await build({ stdin: { contents: "export { businessPackage, addPurchase } from './tests/helpers/business-fixtures'; export { purchasingJourney } from './tests/helpers/purchasing-journey';", resolveDir: process.cwd() }, bundle: true, platform: 'node', format: 'esm', outfile: helper });
const { businessPackage, addPurchase, purchasingJourney } = await import(pathToFileURL(helper).href);
const records = purchasingJourney();
const longId = 'SYNTHETIC-PURCHASE-' + '0123456789'.repeat(6);
addPurchase(records, longId);
for (let i = 0; i < 30; i++) addPurchase(records, `SYNTHETIC-PURCHASE-${String(i).padStart(2, '0')}`);
const fixture = businessPackage(records, { extractionId: 'business-long-layout-1' });
const fixturePath = join(profile, 'synthetic-long-layout.json');
await writeFile(fixturePath, fixture, { flag: 'wx' });
const sha256 = value => createHash('sha256').update(value).digest('hex');
const executablePath = resolve('release/win-unpacked/Esmer Market Analytics.exe');
const result = { date: new Date().toISOString(), expectedScale, executablePath, profile, work, archiveSha256: sha256(await readFile('release/win-unpacked/resources/app.asar')), fixture: { identity: 'business-fixture/business-long-layout-1', sha256: sha256(fixture), bytes: fixture.length, documents: records.documents.length, lines: records.lines.length, suppliers: records.suppliers.length }, checks: {}, screenshots: [] };
const app = await electron.launch({ executablePath, args: [`--user-data-dir=${profile}`], env: { ...process.env, PATH: 'C:/Windows/System32;C:/Windows', NODE_PATH: '', NODE_OPTIONS: '' } });
try {
  const page = await app.firstWindow();
  result.runtime = await app.evaluate(({ app, screen, BrowserWindow }) => ({ packaged: app.isPackaged, versions: process.versions, switches: process.argv, display: screen.getDisplayMatching(BrowserWindow.getAllWindows()[0].getBounds()), minimum: BrowserWindow.getAllWindows()[0].getMinimumSize() }));
  expect(result.runtime.packaged).toBe(true);
  expect(result.runtime.display.scaleFactor).toBe(expectedScale);
  expect(result.runtime.switches.some(value => value.includes('force-device-scale-factor'))).toBe(false);
  await app.evaluate(({ dialog }, path) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [path] }); }, fixturePath);
  await page.getByRole('button', { name: 'Veri paketi içe aktar' }).click();
  await expect(page.locator('.metric').first()).toContainText('200,00 ₺');
  await page.getByRole('button', { name: 'Maliyet ve Alışlar', exact: true }).click();
  await expect(page.locator('.metric').nth(2)).toContainText('40,00 ₺');
  await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(680, 520));
  await expect.poll(() => page.evaluate(() => innerWidth)).toBeLessThanOrEqual(680);
  result.geometry = await page.evaluate(() => ({ width: innerWidth, height: innerHeight, documentWidth: document.documentElement.scrollWidth, devicePixelRatio }));
  expect(result.geometry.devicePixelRatio).toBe(expectedScale);
  expect(result.geometry.documentWidth).toBeLessThanOrEqual(result.geometry.width);
  await expect(page.getByText('Negatif stok kaydı var', { exact: false })).toBeVisible();
  await expect(page.getByText('Fire kayıtları seyrek', { exact: false })).toBeVisible();
  const section = page.locator('section').filter({ has: page.getByRole('heading', { name: 'Alış geçmişi ve tedarikçi iadeleri', exact: true }) });
  const scroll = section.locator('.table-scroll').first();
  await expect(scroll.getByRole('row')).toHaveCount(33);
  await scroll.getByRole('row').nth(1).scrollIntoViewIfNeeded();
  const before = await scroll.evaluate(element => ({ left: element.scrollLeft, width: element.clientWidth, scrollWidth: element.scrollWidth, overflowX: getComputedStyle(element).overflowX }));
  expect(before.scrollWidth).toBeGreaterThan(before.width);
  const box = await scroll.getByRole('row').nth(1).boundingBox();
  const pointer = { x: box.x + 80, y: box.y + box.height / 2 };
  result.pointer = { ...pointer, target: await page.evaluate(({ x, y }) => document.elementFromPoint(x, y)?.outerHTML, pointer) };
  await page.mouse.move(pointer.x, pointer.y);
  await page.mouse.wheel(1600, 0);
  await expect.poll(() => scroll.evaluate(element => element.scrollLeft)).toBeGreaterThan(0);
  const right = await scroll.evaluate(element => element.scrollLeft);
  await page.mouse.wheel(-1600, 0);
  await expect.poll(() => scroll.evaluate(element => element.scrollLeft)).toBe(0);
  result.checks.horizontalWheel = { ...before, right, restored: 0 };
  const opener = scroll.getByRole('button', { name: longId, exact: true });
  await opener.press('Enter');
  const panel = page.getByRole('complementary');
  await expect(panel.getByRole('heading', { name: 'Maliyet ve alış kaynak detayı' })).toBeFocused();
  await expect(panel.getByText(longId, { exact: true })).toBeVisible();
  await panel.getByText(`Satır: ${longId}-line`, { exact: true }).scrollIntoViewIfNeeded();
  expect(await panel.evaluate(element => element.scrollTop)).toBeGreaterThan(0);
  const sourceScreenshot = join(work, `os-${expectedScale}-source.png`);
  await page.screenshot({ path: sourceScreenshot }); result.screenshots.push(sourceScreenshot);
  await page.keyboard.press('Escape');
  await expect(opener).toBeFocused();
  result.checks.keyboardEnterEscapeFocus = true;
  result.checks.verticalHistoryAndSourceScroll = true;
  await page.getByRole('button', { name: 'Maliyet ve Alışlar', exact: true }).scrollIntoViewIfNeeded();
  const overviewScreenshot = join(work, `os-${expectedScale}-overview.png`);
  await page.screenshot({ path: overviewScreenshot }); result.screenshots.push(overviewScreenshot);
  result.checks.sales200CoveredGross40 = true;
  result.status = 'passed';
} catch (error) {
  result.status = 'failed'; result.error = String(error);
  throw error;
} finally {
  await app.close();
  await writeFile(join(work, 'result.json'), JSON.stringify(result, null, 2));
  console.log(JSON.stringify({ work, status: result.status, error: result.error }));
}
