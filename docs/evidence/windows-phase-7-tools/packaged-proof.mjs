import { _electron as electron, expect } from '@playwright/test';
import { mkdtemp, writeFile } from 'node:fs/promises';
import { resolve, join } from 'node:path';
import assert from 'node:assert/strict';
import writeXlsxFile from 'write-excel-file/node';
import { expenseColumns } from './api.mjs';
const scale = Number(process.argv[2] ?? '1.25');
const root = resolve('work/windows-phase-7');
const fixtures = join(root, 'sentetik-İşçilik');
const profile = await mkdtemp(join(root, `packaged-${scale}-`));
const executablePath = resolve('release/win-unpacked/Esmer Market Analytics.exe');
const workbook = join(fixtures, 'excel-kaydedildi.xlsx');
const wideWorkbook = join(profile, 'sentetik-wide.xlsx');
const wide = ['sentetik-wide-1', '15.01.2026', '', 'Sentetik' + 'X'.repeat(70), 'operating-expense', '9999999999999999999999999999999999999999', '0', '9999999999999999999999999999999999999999', 'non-recoverable', 'sentetik-vergi', '', '', '', ''];
await writeFile(wideWorkbook, await writeXlsxFile([expenseColumns, wide, ['sentetik-wide-2', ...wide.slice(1)]].map(row => row.map(value => ({ type: String, value })))).toBuffer());
const app = await electron.launch({ executablePath, args: [`--user-data-dir=${profile}`] });
const proof = { scale, profile, dialogSubstitution: true, assertions: [] };
try {
  const page = await app.firstWindow();
  proof.display = await app.evaluate(({ screen }) => screen.getAllDisplays().map(d => ({ bounds: d.bounds, scale: d.scaleFactor })));
  assert.equal(proof.display[0].scale, scale);
  await page.getByRole('button', { name: 'Giderler', exact: true }).click();
  await page.getByLabel('Dönem', { exact: true }).fill('2026-01');
  await app.evaluate(({ dialog }, path) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [path] }); }, wideWorkbook);
  await page.getByRole('button', { name: 'Excel seç', exact: true }).click();
  await page.getByRole('heading', { name: 'Excel önizlemesi' }).waitFor();
  await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(680, 520));
  await expect.poll(() => page.evaluate(() => innerWidth)).toBeLessThan(700);
  const scroller = page.locator('.table-scroll').first();
  proof.table = await scroller.evaluate(e => ({ client: e.clientWidth, content: e.scrollWidth }));
  assert.ok(proof.table.content > proof.table.client);
  await scroller.hover();
  await page.mouse.wheel(900, 0);
  await expect.poll(() => scroller.evaluate(e => e.scrollLeft)).toBeGreaterThan(0);
  proof.assertions.push('wide preview table scrolls with horizontal wheel at actual Windows scale');
  await expect(page.getByRole('button', { name: 'İçe aktarmayı onayla', exact: true })).toBeDisabled();
  await page.getByLabel('Satır 3: benzer kayda rağmen ayrı gider olarak ekle').check();
  await expect(page.getByRole('button', { name: 'İçe aktarmayı onayla', exact: true })).toBeEnabled();
  await page.screenshot({ path: join(root, `scale-${scale}-preview.png`), fullPage: true });
  await page.getByRole('button', { name: 'Önizlemeyi kapat', exact: true }).click();
  await app.evaluate(({ dialog }, path) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [path] }); }, workbook);
  await page.getByRole('button', { name: 'Excel seç', exact: true }).click();
  await page.getByRole('button', { name: 'İçe aktarmayı onayla', exact: true }).click();
  await expect(page.getByRole('button', { name: 'İncele / düzelt', exact: true })).toHaveCount(2);
  await page.getByRole('button', { name: 'İncele / düzelt', exact: true }).first().focus();
  await page.keyboard.press('Enter');
  await expect(page.getByRole('heading', { name: 'Gideri incele ve düzelt' })).toBeFocused();
  await page.getByLabel('Değişiklik gerekçesi').scrollIntoViewIfNeeded();
  await expect(page.getByLabel('Değişiklik gerekçesi')).toBeInViewport();
  await page.screenshot({ path: join(root, `scale-${scale}-correction.png`), fullPage: true });
  proof.assertions.push('keyboard opens correction with heading focus; reason is reachable at minimum window');
  await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(1120, 780));
  await page.getByRole('button', { name: 'Ana sayfaya dön', exact: true }).click();
  await app.evaluate(({ dialog }, path) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [path] }); }, join(fixtures, 'sentetik-satis.json'));
  await page.getByRole('button', { name: 'Veri paketi içe aktar', exact: true }).click();
  const operating = page.getByRole('region', { name: 'Faaliyet sonucu', exact: true });
  await expect(operating).toContainText('Faaliyet kârı hesaplanamıyor — gider verileri eksik.');
  await page.getByRole('button', { name: 'Giderler', exact: true }).click();
  await page.getByLabel('Bu dönemin giderlerini inceledim ve eksiksiz olduğunu onaylıyorum').check();
  await page.getByLabel('İnceleme açıklaması').fill('Sentetik test, gerçek sahip onayı değildir');
  await page.getByRole('button', { name: 'Eksiksizliği onayla', exact: true }).click();
  await expect(page.getByText('Dönemin giderleri eksiksiz olarak onaylandı', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Satış Özeti', exact: true }).click();
  await operating.getByRole('button', { name: 'Raporu yeni giderlerle aç' }).click();
  await expect(operating.locator('.operating-value')).toHaveText('150,00 ₺');
  await operating.getByText('Hesaplama ve sabit kayıtlar', { exact: true }).click();
  await expect(operating).toContainText('Kapsanan tahmini brüt kâr: 200,00 ₺');
  await expect(operating).toContainText('Hesaba alınan gider: 50,00 ₺');
  await expect(operating).toContainText('sentetik-katki');
  proof.estimated = await operating.innerText();
  await page.screenshot({ path: join(root, `scale-${scale}-operating.png`), fullPage: true });
  await page.getByRole('button', { name: 'Giderler', exact: true }).click();
  await page.getByLabel('İnceleme açıklaması').fill('Sentetik onayı geri alma');
  await page.getByRole('button', { name: 'Eksiksizlik onayını kaldır', exact: true }).click();
  await expect(page.getByText('Eksiksizlik onayı kaldırıldı.', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Satış Özeti', exact: true }).click();
  await expect(operating.locator('.operating-value')).toHaveText('150,00 ₺');
  await operating.getByRole('button', { name: 'Raporu yeni giderlerle aç' }).click();
  await expect(operating).toContainText('Faaliyet kârı hesaplanamıyor — gider verileri eksik.');
  proof.assertions.push('gross 200 minus expense 50 gives estimated 150; owner contribution 500 excluded', 'revocation preserves pinned 150 until reopening, then withholds result');
  proof.january = await page.evaluate(() => window.esmer.queryExpenses({ period: '2026-01' }));
  proof.february = await page.evaluate(() => window.esmer.queryExpenses({ period: '2026-02' }));
  assert.equal(proof.february.incurred, '0'); assert.equal(proof.february.payments, '50');
} finally { await app.close(); }
const restarted = await electron.launch({ executablePath, args: [`--user-data-dir=${profile}`] });
try {
  const page = await restarted.firstWindow();
  await page.getByRole('button', { name: 'Giderler', exact: true }).click();
  await restarted.evaluate(({ dialog }, path) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [path] }); }, workbook);
  const before = await page.evaluate(() => window.esmer.queryExpenses({ period: '2026-01' }));
  assert.deepEqual(before, proof.january);
  const preview = await page.evaluate(() => window.esmer.previewExpenses());
  assert.equal(preview.alreadyImported, true);
  const result = await page.evaluate(previewId => window.esmer.confirmExpenses({ previewId, keepCandidateRows: [] }), preview.previewId);
  assert.equal(result.status, 'already-imported');
  assert.deepEqual(await page.evaluate(() => window.esmer.queryExpenses({ period: '2026-01' })), before);
  proof.assertions.push('restart retains history and revoked review; identical bytes do not append revisions or batches');
} finally { await restarted.close(); }
await writeFile(join(root, `packaged-proof-${scale}.json`), JSON.stringify(proof, null, 2));
console.log(JSON.stringify({ scale, profile, assertions: proof.assertions }));


