import { test, expect, _electron as electron } from "@playwright/test";
import { mkdtemp, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { journeyRecords, salesPackage } from "../helpers/sales-fixtures";

const executablePath = process.env.ESMER_EXECUTABLE ?? (process.platform === "darwin" ? resolve(`release/mac${process.arch === "arm64" ? "-arm64" : ""}/Esmer Market Analytics.app/Contents/MacOS/Esmer Market Analytics`) : process.platform === "win32" ? resolve("release/win-unpacked/Esmer Market Analytics.exe") : resolve("release/linux-unpacked/esmer-market-analytics"));

test("packaged sales workspace follows a number through product, document and source with keyboard", async () => {
  const userData = await mkdtemp(join(tmpdir(), "esmer-sales-"));
  const packagePath = join(userData, "synthetic-sales.json");
  const records = journeyRecords();
  records.lines.find(line => line.id === "L003")!.quantity = "3.000";
  await writeFile(packagePath, salesPackage(records));
  const app = await electron.launch({ executablePath, args: [`--user-data-dir=${userData}`] });
  try {
    const page = await app.firstWindow();
    await app.evaluate(({ dialog }, path) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [path] }); }, packagePath);
    await page.getByRole("button", { name: "Veri paketi içe aktar" }).click();
    await page.getByRole("button", { name: "Satış Özeti", exact: true }).click();
    await expect(page.getByRole("heading", { name: "Satış Özeti", exact: true })).toBeVisible();
    await expect(page.getByLabel("Dönem")).toHaveValue("2025-09");
    await expect(page.locator(".metric").first()).toContainText("365,00 ₺");
    await expect(page.locator(".metric").nth(1)).toContainText("3");
    await expect(page.locator(".metric").nth(2)).toContainText("133,33 ₺");
    await page.screenshot({ path: "test-results/phase-5-sales-overview.png", fullPage: true });
    await page.setViewportSize({ width: 680, height: 720 });
    const bars = await page.locator(".chart rect").evaluateAll(rects => rects.map(rect => rect.getBoundingClientRect().height));
    expect(bars[2] / bars[0]).toBeCloseTo(200 / 70, 4);
    await page.screenshot({ path: "test-results/phase-5-sales-small-window.png", fullPage: true });
    await page.setViewportSize({ width: 1120, height: 850 });
    await page.getByRole("button", { name: "İçecekler", exact: true }).click();
    await expect(page.getByRole("heading", { name: "Kategori / Ürün Detayı", exact: true })).toBeVisible();
    await expect(page.getByRole("button", { name: "Gazoz", exact: true })).toBeVisible();
    await expect(page.locator(".comparison-boundaries")).toContainText("01.08.2025 – 03.08.2025");
    await page.getByRole("button", { name: "Satış Özeti", exact: true }).click();
    await page.getByLabel("Ürün ara").fill("İÇME");
    await page.getByRole("button", { name: "İçme suyu", exact: true }).press("Enter");
    await expect(page.getByRole("heading", { name: "İşlemler", exact: true })).toBeVisible();
    await page.getByRole("button", { name: "S002", exact: true }).press("Enter");
    const panel = page.getByRole("complementary");
    await expect(panel.getByRole("heading", { name: "İşlem Detayı" })).toBeFocused();
    await expect(panel.locator(".document-totals")).toContainText("130,00 ₺");
    await expect(panel.locator(".selected-total")).toContainText("60,00 ₺");
    await expect(panel.getByRole("heading", { name: "Gazoz", exact: true })).toBeVisible();
    await page.screenshot({ path: "test-results/phase-5-sales-receipt.png" });
    await panel.getByRole("button", { name: "Kaynak detayını göster" }).first().press("Enter");
    await expect(panel.getByRole("heading", { name: "Kaynak Detayı" })).toBeFocused();
    await expect(panel.getByText("S002 / L003", { exact: true })).toBeVisible();
    await expect(panel.getByText("sales-1", { exact: true })).toBeVisible();
    await panel.getByText("Teknik ayrıntılar", { exact: true }).click();
    await expect(panel.getByText("3,000 / adet", { exact: true })).toBeVisible();
    await expect(panel.getByText("water / drinks", { exact: true })).toBeVisible();
    await page.screenshot({ path: "test-results/phase-5-sales-source.png" });
    await panel.getByRole("button", { name: "İşleme dön" }).press("Enter");
    await page.keyboard.press("Escape");
    await expect(page.getByRole("button", { name: "S002", exact: true })).toBeFocused();
    await expect(page.getByLabel("Ürün ara")).toHaveValue("İÇME");
    await page.getByRole("button", { name: "S002", exact: true }).press("Enter");
    await panel.getByRole("button", { name: "Kaynak detayını göster" }).first().click();
    await writeFile(packagePath, salesPackage(journeyRecords(), { extractionId: "sales-2" }));
    await page.getByRole("button", { name: "Veri paketi içe aktar" }).click();
    await expect(page.getByText("Yeni veri sürümü hazır", { exact: true })).toBeVisible();
    await expect(panel.getByText("sales-1", { exact: true })).toBeVisible();
    await expect(page.getByLabel("Ürün ara")).toHaveValue("İÇME");
    await page.screenshot({ path: "test-results/phase-5-sales-journey.png" });
    await panel.getByRole("button", { name: "Kapat" }).click();
    await page.getByRole("button", { name: "Raporu yenile" }).click();
    await expect(page.getByRole("heading", { name: "Satış Özeti", exact: true })).toBeVisible();
    await expect(page.getByText("Yeni veri sürümü hazır", { exact: true })).toHaveCount(0);
    await page.getByRole("button", { name: "Tüm işlemleri göster" }).click();
    await page.getByLabel("İşlem türü").selectOption("customer-return");
    await expect(page.getByRole("button", { name: "R001", exact: true })).toBeVisible();
    await expect(page.getByRole("button", { name: "S002", exact: true })).toHaveCount(0);
    await expect(page.locator(".return-row")).toContainText("-35,00 ₺");
    await page.screenshot({ path: "test-results/phase-5-sales-return.png" });
    await page.getByRole("button", { name: "R001", exact: true }).click();
    await panel.getByRole("button", { name: "Kaynak detayını göster" }).click();
    await expect(panel.getByText("sales-2", { exact: true })).toBeVisible();
  } finally { await app.close(); await rm(userData, { recursive: true, force: true }); }
});

test("packaged sales workspace distinguishes discrepancies, excluded contributions and missing coverage", async () => {
  const userData = await mkdtemp(join(tmpdir(), "esmer-sales-warnings-"));
  const packagePath = join(userData, "synthetic-sales.json");
  const records = journeyRecords();
  records.documents.find(document => document.id === "S002")!.sales!.net = "132";
  records.lines.find(line => line.id === "L005")!.sales!.meaning = "unknown";
  await writeFile(packagePath, salesPackage(records));
  const app = await electron.launch({ executablePath, args: [`--user-data-dir=${userData}`] });
  try {
    const page = await app.firstWindow();
    await app.evaluate(({ dialog }, path) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [path] }); }, packagePath);
    await page.getByRole("button", { name: "Veri paketi içe aktar" }).click();
    await page.getByRole("button", { name: "Satış Özeti", exact: true }).click();
    await expect(page.getByRole("heading", { name: "Satış Özeti", exact: true })).toBeVisible();
    await expect(page.getByText("Kısmi dönem · Uzlaşma eksik", { exact: true })).toBeVisible();
    await page.getByRole("button", { name: "S003", exact: true }).click();
    const panel = page.getByRole("complementary");
    await expect(panel.getByText("Net satış katkısı bilinmiyor; sıfır sayılmaz.", { exact: false }).first()).toBeVisible();
    await expect(panel.locator(".selected-total")).toContainText("Hesaplama dışında");
    await panel.getByRole("button", { name: "Kaynak detayını göster" }).first().click();
    await expect(panel.getByRole("heading", { name: "Kaynak Detayı" })).toBeVisible();
    await expect(panel.getByText("S003 / L005", { exact: true })).toBeVisible();
    await expect(panel.getByText("sales-1", { exact: true })).toBeVisible();
    await expect(panel.getByText("synthetic-sales-v1", { exact: true })).toBeVisible();
    await expect(panel.getByText("Hesaplanmadı; bu satır net satış katkısı olarak kullanılmadı.", { exact: true })).toBeVisible();
    await expect(panel.getByText("120,00 ₺ / 6,00 ₺ / 126,00 ₺", { exact: true })).toBeVisible();
    await page.screenshot({ path: "test-results/phase-5-sales-excluded-source.png" });
    await panel.getByRole("button", { name: "İşleme dön" }).click();
    await expect(panel.locator(".selected-total")).toContainText("Hesaplama dışında");
    await panel.getByRole("button", { name: "Kapat" }).click();
    await page.getByRole("button", { name: "Tüm işlemleri göster" }).click();
    await page.getByRole("button", { name: "S002", exact: true }).click();
    await expect(panel.getByText("Uzlaşma eksik", { exact: true })).toBeVisible();
    await expect(panel.getByText("Kaydedilen başlık neti:", { exact: false })).toContainText("132,00 ₺");
    await expect(panel.getByText("Kaydedilen başlık neti:", { exact: false })).toContainText("130,00 ₺");
    await page.screenshot({ path: "test-results/phase-5-sales-discrepancy.png" });
    await panel.getByRole("button", { name: "Kapat" }).click();
    await page.getByLabel("Dönem").fill("2025-10");
    await expect(page.getByText("Dönem verisi yok · Uzlaşma eksik", { exact: true })).toBeVisible();
    await expect(page.locator(".metric").first()).toContainText("Veri yok");
    await expect(page.locator(".metric").first()).not.toContainText("0,00 ₺");
  } finally { await app.close(); await rm(userData, { recursive: true, force: true }); }
});
